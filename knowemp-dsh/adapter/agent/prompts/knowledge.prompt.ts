/**
 * 知识检索后的终答说明。角色仍是 KnowEmp 助手（与 TDS 终答同一套），
 * 只补充切片用法，避免切成「只复述条文」的问答机器人。
 */
export const KNOWLEDGE_QA_PROMPT = `请根据已有工具结果直接用中文回答用户，不要再调用工具。

知识切片不是最终答案，用法与查 TDS 列表后作答相同：先理解用户这句要什么，再用相关结果回答。
- 只根据本轮工具结果作答；本轮没有的制度不要用上一轮对话里的旧条文代替
- 条文、数据以相关切片为准，不要编新规定；可以把规则用到用户给的条件上
- 用户还问了切片没有的安排（行程、地点等），用常识作答，并写清哪部分来自制度、哪部分不是制度；没写到的制度不要编
- 引用制度时点明切片标题或【标准库】/【其他库】，不要伪造出处
- 某一检索步骤未命中时，只说明该部分没有查到，用已命中的继续答
- 切片可能来自标准库或其他库（标题带【标准库】/【其他库】），按与问题是否相关取用，不要因为库别丢掉相关条文
- 无关切片忽略，不要转述成「另外 / 此外」
- 保留相关切片中的图片（完整 https 链接，不要改回 file_ 编号）、代码块、表格
- 图文对照先写说明、图片放在说明下面，不要改成表格
- 不要在正文末尾再列「你可以继续问」，界面会单独给出可点追问
- 使用与用户问题相同的语言`;

export const KNOWLEDGE_QA_COMPACT_HINT =
  '按用户问题作答；条文以相关切片为准并点明【标准库】/【其他库】或标题；可应用到用户条件上；切片没有的行程地点用常识并标明；某一检索未命中只说明该部分没有；无关切片忽略；保留图片（完整 https）、代码块、表格；图文对照先说明后放图。';

export const SYNTHESIS_QA_PROMPT = `请综合本轮所有工具结果直接用中文回答用户，不要再调用工具。

- 知识切片覆盖制度、技术标准、生产经验；TDS 结果覆盖光源、材料、供应商目录
- 两边都有证据时合并成一个答案，不要拆成互不相关的两段流水账
- 若知识切片写了推荐材料、牌号、树脂或颜色，目录结果必须对照这些约束再叠加用户条件；不要抛开规范另推一套料
- 没有材料/光源列表时，不要编造推荐型号或料号；明说目录还没查到
- 某一源未命中或没有工具结果，就明说该部分没有查到，用另一源能答的继续答；不要把「知识库没有命中」说成整个问题无法回答
- 引用制度时点明切片标题或【标准库】/【其他库】，不要伪造出处
- 知识切片可能同时来自标准库与其他库，按相关性取用
- 条文、参数以工具结果为准，不要编；无关切片忽略
- 保留相关切片中的图片（完整 https 链接）、代码块、表格
- 不要在正文末尾再列推荐追问，界面会单独给出可点选项
- 使用与用户问题相同的语言`;

export function knowledgeAnswerInstruction(userMessage: string): string {
  const question = userMessage.trim() || '用户问题';
  return `${KNOWLEDGE_QA_PROMPT}

用户问题：${question}`;
}

export function synthesisAnswerInstruction(userMessage: string): string {
  const question = userMessage.trim() || '用户问题';
  return `${SYNTHESIS_QA_PROMPT}

用户问题：${question}`;
}

